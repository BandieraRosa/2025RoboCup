/**
 * @brief       GC0308 IIC写寄存器
 * @param       reg_addr: 寄存器地址
 * @param       reg_data: 寄存器数据
 * @retval      无
 */
static void gc0308_iic_send_data(uint8_t reg_addr, uint8_t reg_data)
{
    uint8_t data[2];

    data[0] = reg_addr;
    data[1] = reg_data;
    i2c_send_data(I2C_DEVICE_2, &data[0], 2);
}

/**
 * @brief       GC0308 IIC读寄存器
 * @param       reg_addr: 寄存器地址
 * @retval      寄存器数据
 */
static uint8_t gc0308_iic_receive_data(uint8_t reg_addr)
{
    uint8_t data[2];

    data[0] = reg_addr;
    i2c_recv_data(I2C_DEVICE_2, &data[0], 1, &data[1], 1);

    return data[1];
}

/**
 * @brief       GC0308初始化
 * @param       无
 * @retval      0, 初始化成功
 */
static int gc0308_init(void)
{
    uint8_t product_id;
    uint16_t index;

    /* Initialize IIC(Not SCCB but IIC)  */
    fpioa_set_function(CAMERA_SDA_PIN, FUNC_I2C2_SDA);
    fpioa_set_function(CAMERA_SCL_PIN, FUNC_I2C2_SCLK);
    i2c_init(I2C_DEVICE_2, GC0308_ADDR, 7, 400000);

    /* Check product ID */
    gc0308_iic_send_data(0xFE, 0x00);
    product_id = gc0308_iic_receive_data(0x00);
    if (product_id != GC0308_PID)
    {
        return 1;
    }

    /* Software reset */
    gc0308_iic_send_data(0xFE, 0xF0);
    msleep(80);

    /* Initlize registers */
    for (index=0; index<(sizeof(gc0308_config)/sizeof(gc0308_config[0])); index++)
    {
        gc0308_iic_send_data(gc0308_config[index][0], gc0308_config[index][1]);
    }

    return 0;
}

