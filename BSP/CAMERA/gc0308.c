/**
 * @brief       设置图片分辨率大小
 * @param       width  : 图片的宽度
 * @param       height : 图片的高度
 * @retval      0, 操作成功
 */
static int gc0308_set_framesize(uint16_t width, uint16_t height)
{
    struct subsample_cfg {
        uint16_t ratio_numerator;
        uint16_t ratio_denominator;
        uint8_t reg54;
        uint8_t reg56;
        uint8_t reg57;
        uint8_t reg58;
        uint8_t reg59;
    };
    const struct subsample_cfg subsample_cfgs[] = {
        { 84, 420, 0x55, 0x00, 0x00, 0x00, 0x00},
        {105, 420, 0x44, 0x00, 0x00, 0x00, 0x00},
        {140, 420, 0x33, 0x00, 0x00, 0x00, 0x00},
        {210, 420, 0x22, 0x00, 0x00, 0x00, 0x00},
        {240, 420, 0x77, 0x02, 0x46, 0x02, 0x46},
        {252, 420, 0x55, 0x02, 0x04, 0x02, 0x04},
        {280, 420, 0x33, 0x02, 0x00, 0x02, 0x00},
        {420, 420, 0x11, 0x00, 0x00, 0x00, 0x00},
    };
    const struct subsample_cfg *cfg = NULL;

    uint16_t win_w = width;
    uint16_t win_h = height;
    uint16_t col_s = (640 - win_w) >> 1;
    uint16_t row_s = (480 - win_h) >> 1;
    uint8_t i;

    for (i = 0; i < (sizeof(subsample_cfgs) / sizeof(subsample_cfgs[0])); i++)
    {
        cfg = &subsample_cfgs[i];
        if ((640 * cfg->ratio_numerator / cfg->ratio_denominator >= width) && (480 * cfg->ratio_numerator / cfg->ratio_denominator >= height))
        {
            win_w = width * cfg->ratio_denominator / cfg->ratio_numerator;
            win_h = height * cfg->ratio_denominator / cfg->ratio_numerator;
            col_s = (640 - win_w) >> 1;
            row_s = (480 - win_h) >> 1;
            break;
        }
    }

    gc0308_iic_send_data(0xFE, 0x00);
    gc0308_iic_send_data(0x05, (row_s >> 8) & 0xFF);
    gc0308_iic_send_data(0x06, row_s & 0xFF);
    gc0308_iic_send_data(0x07, (col_s >> 8) & 0xFF);
    gc0308_iic_send_data(0x08, col_s & 0xFF);
    gc0308_iic_send_data(0x09, ((win_h + 8) >> 8) & 0xFF);
    gc0308_iic_send_data(0x0A, (win_h + 8) & 0xFF);
    gc0308_iic_send_data(0x0B, ((win_w + 8) >> 8) & 0xFF);
    gc0308_iic_send_data(0x0C, (win_w + 8) & 0xFF);
    gc0308_iic_send_data(0xFE, 0x01);
    gc0308_iic_send_data(0x54, cfg->reg54);
    gc0308_iic_send_data(0x56, cfg->reg56);
    gc0308_iic_send_data(0x57, cfg->reg57);
    gc0308_iic_send_data(0x58, cfg->reg58);
    gc0308_iic_send_data(0x59, cfg->reg59);
    gc0308_iic_send_data(0xFE, 0x00);

    msleep(30);

    return 0;
}

/**
 * @brief       图片水平翻转
 * @param       enable  : 0：不翻转 1：翻转
 * @retval      0, 操作成功
 */
static int gc0308_set_hmirror(uint8_t enable)
{
    uint8_t reg14;

    gc0308_iic_send_data(0xFE, 0x00);
    reg14 = gc0308_iic_receive_data(0x14);
    reg14 &= ~(1 << 0);
    if (enable != 0)
    {
        reg14 |= (1 << 0);
    }
    gc0308_iic_send_data(0x14, reg14);

    return 0;
}

/**
 * @brief       图片垂直翻转
 * @param       enable  : 0：不翻转 1：翻转
 * @retval      0, 操作成功
 */
static int gc0308_set_vflip(uint8_t enable)
{
    uint8_t reg14;

    gc0308_iic_send_data(0xFE, 0x00);
    reg14 = gc0308_iic_receive_data(0x14);
    reg14 &= ~(1 << 1);
    if (enable != 0)
    {
        reg14 |= (1 << 1);
    }
    gc0308_iic_send_data(0x14, reg14);

    return 0;
}

